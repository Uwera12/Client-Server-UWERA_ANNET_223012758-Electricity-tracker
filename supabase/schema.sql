-- =====================================================================
-- Electricity Usage Tracker  |  Supabase (Postgres) schema
-- Run in: Supabase dashboard -> SQL Editor -> New query -> paste -> Run
-- Safe to re-run: it drops the project's tables first.
-- =====================================================================

drop table if exists readings     cascade;
drop table if exists meters       cascade;
drop table if exists tariff_bands cascade;
drop table if exists profiles     cascade;

-- ---------- profiles: one row per Supabase Auth user (holds the role) ----------
create table profiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  full_name  text,
  role       text not null default 'household' check (role in ('household')),
  created_at timestamptz not null default now()
);

-- Create a profile automatically whenever someone signs up.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, new.raw_user_meta_data ->> 'full_name')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Back-fill profiles for users who signed up before this script ran.
insert into profiles (id)
select id from auth.users
on conflict (id) do nothing;

-- ---------- meters: a household owns one or more meters ----------
create table meters (
  id           bigint generated by default as identity primary key,
  household_id uuid        not null references auth.users(id) on delete cascade,
  name         text        not null check (char_length(name) between 1 and 100),
  meter_number text        not null unique check (char_length(meter_number) between 1 and 50),
  location     text        check (char_length(location) <= 200),
  created_at   timestamptz not null default now()
);

-- ---------- readings: cumulative kWh shown on the meter on a given date ----------
create table readings (
  id         bigint generated by default as identity primary key,
  meter_id   bigint        not null references meters(id) on delete cascade,
  kwh        numeric(10,2) not null check (kwh >= 0),
  read_date  date          not null,
  created_at timestamptz   not null default now(),
  unique (meter_id, read_date)          -- one reading per meter per day
);
create index readings_meter_date_idx on readings (meter_id, read_date);

-- ---------- tariff_bands: block tariff used to compute the bill ----------
-- to_kwh NULL means "no upper limit". Rates are SAMPLE values for teaching:
-- edit them to match your utility's real tariff.
create table tariff_bands (
  id       int primary key generated by default as identity,
  name     text          not null,
  from_kwh numeric(10,2) not null check (from_kwh >= 0),
  to_kwh   numeric(10,2),
  rate_rwf numeric(10,2) not null check (rate_rwf >= 0),
  check (to_kwh is null or to_kwh > from_kwh)
);

insert into tariff_bands (name, from_kwh, to_kwh, rate_rwf) values
  ('Band 1 (lifeline)',  0,  20, 89),
  ('Band 2',            20,  50, 310),
  ('Band 3',            50, null, 369);

-- ---------- Row Level Security ----------
-- Django connects with the database owner role, which BYPASSES RLS, so Django
-- enforces ownership itself. RLS protects anyone who talks to Supabase directly
-- (e.g. with the anon key from the browser): they only ever see their own rows.
alter table profiles     enable row level security;
alter table meters       enable row level security;
alter table readings     enable row level security;
alter table tariff_bands enable row level security;

create policy "own profile"      on profiles for select to authenticated using (id = auth.uid());
create policy "own meters"       on meters   for all    to authenticated
  using (household_id = auth.uid()) with check (household_id = auth.uid());
create policy "own readings"     on readings for all    to authenticated
  using (exists (select 1 from meters m where m.id = readings.meter_id and m.household_id = auth.uid()))
  with check (exists (select 1 from meters m where m.id = readings.meter_id and m.household_id = auth.uid()));
create policy "tariffs readable" on tariff_bands for select to authenticated using (true);
